def normalize_mac(mac_str: str) -> str:
    """Normalise une adresse MAC au format AA:BB:CC:DD:EE:FF."""
    if not mac_str:
        return ""
    cleaned = mac_str.strip().upper().replace("-", ":").replace(".", ":")
    parts = [p.zfill(2) for p in cleaned.split(":") if p]
    if len(parts) == 6 and all(len(p) == 2 for p in parts):
        return ":".join(parts)
    return cleaned


def lookup_vendor(mac_str: str) -> str:
    """Retourne le constructeur associé à l'adresse MAC ou détecte une MAC aléatoire (LAA)."""
    mac = normalize_mac(mac_str)
    if not mac or len(mac) < 8:
        return ""

    prefix = mac[:8]
    if prefix in OUI_PREFIXES:
        return OUI_PREFIXES[prefix]

    # Détection des adresses MAC localement administrées (LAA / MAC privée iOS/Android/Windows)
    try:
        first_byte = int(mac[:2], 16)
        if first_byte & 0b00000010:
            return "Adresse MAC Privée / Aléatoire (LAA)"
    except ValueError:
        pass

    return "Constructeur inconnu"
